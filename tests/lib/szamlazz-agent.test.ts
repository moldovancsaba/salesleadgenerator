import { describe, it, expect } from 'vitest';
import {
  buildSzamlazzXml,
  parseSzamlazzResponse,
  buildSzamlazzQueryXml,
} from '../../lib/szamlazz-agent';

describe('Számlázz.hu Agent (Issue 291)', () => {
  it('builds compliant XML for proforma díjbekérő with multi-line items', () => {
    const xml = buildSzamlazzXml({
      credentials: { apiKey: 'test-agent-key' },
      currency: 'EUR',
      orderNumber: 'Q-2026-001',
      buyer: {
        name: 'Padel Club International',
        country: 'South Africa',
        city: 'Cape Town',
        address: '12 Main Road',
        email: 'billing@padelclub.co.za',
      },
      items: [
        {
          name: 'Padel Court Booking SaaS (Annual)',
          quantity: 1,
          unit: 'year',
          netUnitPrice: 1200,
          vatRate: '0',
          netTotal: 1200,
          vatTotal: 0,
          grossTotal: 1200,
          comment: 'Turnkey Club Management & WhatsApp Bookings',
        },
      ],
      isProforma: true,
      comment: 'Thank you for your business. Generated by SLG for Moldován Csaba Kft.',
    });

    expect(xml).toContain('<szamlaagentkulcs>test-agent-key</szamlaagentkulcs>');
    expect(xml).toContain('<dijbekero>true</dijbekero>');
    expect(xml).toContain('<penznem>EUR</penznem>');
    expect(xml).toContain('<rendelesSzam>Q-2026-001</rendelesSzam>');
    expect(xml).toContain('<nev>Padel Club International</nev>');
    expect(xml).toContain('<orszag>South Africa</orszag>');
    expect(xml).toContain('<email>billing@padelclub.co.za</email>');
    expect(xml).toContain('<megnevezes>Padel Court Booking SaaS (Annual)</megnevezes>');
    expect(xml).toContain('<nettoErtek>1200.00</nettoErtek>');
  });

  it('parses successful Számlázz.hu response correctly', () => {
    const mockSuccessResponse = `<?xml version="1.0" encoding="UTF-8"?>
<xmlszamlavalasz xmlns="http://www.szamlazz.hu/xmlszamlavalasz">
  <sikeres>true</sikeres>
  <szamlaszam>DIJ-2026-042</szamlaszam>
  <szamlaNettoVegosszeg>1200.00</szamlaNettoVegosszeg>
  <szamlaBruttoVegosszeg>1200.00</szamlaBruttoVegosszeg>
  <pdf>JVBERi0xLjQKJcOkw7zDtsOfC...</pdf>
</xmlszamlavalasz>`;

    const parsed = parseSzamlazzResponse(mockSuccessResponse);
    expect(parsed.ok).toBe(true);
    expect(parsed.invoiceNumber).toBe('DIJ-2026-042');
    expect(parsed.netTotal).toBe(1200);
    expect(parsed.grossTotal).toBe(1200);
    expect(parsed.pdfBase64).toContain('JVBERi0x');
  });

  it('parses error response and extracts hibauzenet and hibakod', () => {
    const mockErrorResponse = `<?xml version="1.0" encoding="UTF-8"?>
<xmlszamlavalasz xmlns="http://www.szamlazz.hu/xmlszamlavalasz">
  <sikeres>false</sikeres>
  <hibakod>56</hibakod>
  <hibauzenet>Érvénytelen számla agent kulcs</hibauzenet>
</xmlszamlavalasz>`;

    const parsed = parseSzamlazzResponse(mockErrorResponse);
    expect(parsed.ok).toBe(false);
    expect(parsed.errorCode).toBe('56');
    expect(parsed.error).toBe('Érvénytelen számla agent kulcs');
  });

  it('builds query XML for checking invoice status', () => {
    const xml = buildSzamlazzQueryXml('agent-key-123', 'DIJ-2026-042');
    expect(xml).toContain('<szamlaagentkulcs>agent-key-123</szamlaagentkulcs>');
    expect(xml).toContain('<szamlaszam>DIJ-2026-042</szamlaszam>');
  });
});
