import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';
import { LANDING_CONTENT } from '@/content/landing';

const root = join(__dirname, '..', '..');

describe('Landing Page Content and Presentation Decoupling (Issue 287)', () => {
  it('defines structured, typed landing content separated from page components', () => {
    expect(LANDING_CONTENT).toBeDefined();
    expect(LANDING_CONTENT.navigation.brandName).toBe('Sales Lead Generator');
    expect(LANDING_CONTENT.hero.title).toContain('Turn raw prospect accounts into closed deals');
    expect(LANDING_CONTENT.metrics.length).toBeGreaterThanOrEqual(4);
    expect(LANDING_CONTENT.valuePillars.pillars.length).toBeGreaterThanOrEqual(3);
    expect(LANDING_CONTENT.features.items.length).toBeGreaterThanOrEqual(6);
    expect(LANDING_CONTENT.workflow.steps.length).toBeGreaterThanOrEqual(4);
    expect(LANDING_CONTENT.pricing.tiers.length).toBeGreaterThanOrEqual(3);
    expect(LANDING_CONTENT.faq.items.length).toBeGreaterThanOrEqual(4);
  });

  it('renders landing page component from decoupled LANDING_CONTENT', () => {
    const pageFile = readFileSync(join(root, 'app', 'page.tsx'), 'utf8');
    expect(pageFile).toContain("from '@/content/landing'");
    expect(pageFile).toContain('LANDING_CONTENT');
    expect(pageFile).toContain('useAuth()');
    expect(pageFile).toContain('styles.landingRoot');
    expect(pageFile).toContain('styles.hero');
    expect(pageFile).toContain('styles.sectionAlt');
    expect(pageFile).toContain('styles.pricingGrid');
    expect(pageFile).toContain('styles.faqContainer');
  });

  it('provides comprehensive value propositions and compliance commitments', () => {
    const content = LANDING_CONTENT;
    const hasPrivacyCommitment = content.valuePillars.pillars.some((p) =>
      p.title.toLowerCase().includes('mailbox') || p.title.toLowerCase().includes('isolation')
    );
    expect(hasPrivacyCommitment).toBe(true);

    const hasGoogleLimitedUseFaq = content.faq.items.some((item) =>
      item.question.toLowerCase().includes('google api') || item.answer.toLowerCase().includes('limited use')
    );
    expect(hasGoogleLimitedUseFaq).toBe(true);
  });

  it('maintains clean footer navigation referencing legal documentation and release notes', () => {
    const content = LANDING_CONTENT;
    const links = content.footer.links.map((l) => l.href);
    expect(links).toContain('/privacy');
    expect(links).toContain('/terms');
    expect(links).toContain('/whats-new');
  });

  it('contains no forbidden AI assistant branding per AGENTS.md Rule 8', () => {
    const content = readFileSync(join(root, 'content', 'landing.ts'), 'utf8');
    const prohibitedWords = ['claude', 'gemini', 'chatgpt', 'copilot', 'antigravity'];
    for (const word of prohibitedWords) {
      expect(content.toLowerCase()).not.toContain(`co-authored by ${word}`);
      expect(content.toLowerCase()).not.toContain(`generated by ${word}`);
    }
  });
});
