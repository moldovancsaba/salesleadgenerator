import { buildSzamlazzXml, parseSzamlazzResponse, type CreateProformaParams, type SzamlazzAgentResponse } from './szamlazz-agent';
import type { Db } from 'mongodb';
import { ObjectId } from 'mongodb';

export const SZAMLAZZ_ENDPOINT = 'https://www.szamlazz.hu/szamla/';

export interface SzamlazzClientConfig {
  apiKey?: string;
  endpoint?: string;
  fetchFn?: typeof fetch;
}

export class SzamlazzClient {
  private apiKey: string;
  private endpoint: string;
  private fetchFn: typeof fetch;

  constructor(config: SzamlazzClientConfig = {}) {
    this.apiKey = config.apiKey || process.env.SZAMLAZZ_AGENT_KEY || '';
    this.endpoint = config.endpoint || SZAMLAZZ_ENDPOINT;
    this.fetchFn = config.fetchFn || fetch;
  }

  /**
   * Submits an XML request to Számlázz.hu via multipart/form-data with field action-xmlagentxmlfile.
   */
  async submitXml(xmlContent: string): Promise<SzamlazzAgentResponse> {
    try {
      const formData = new FormData();
      const blob = new Blob([xmlContent], { type: 'application/xml' });
      formData.append('action-xmlagentxmlfile', blob, 'request.xml');

      const res = await this.fetchFn(this.endpoint, {
        method: 'POST',
        body: formData,
      });

      const responseText = await res.text();
      return parseSzamlazzResponse(responseText);
    } catch (err: any) {
      return {
        ok: false,
        error: `Számlázz.hu network request failed: ${err?.message || String(err)}`,
      };
    }
  }

  /**
   * Generates a proforma díjbekérő.
   */
  async createProforma(params: Omit<CreateProformaParams, 'credentials'>): Promise<SzamlazzAgentResponse> {
    const xml = buildSzamlazzXml({
      ...params,
      credentials: { apiKey: this.apiKey },
      isProforma: true,
    });
    return this.submitXml(xml);
  }
}

/**
 * Orchestrates creating a proforma díjbekérő directly from a signed quote.
 */
export async function issueProformaForQuote(
  db: Db,
  params: {
    quoteId: string;
    brand: string;
    tenantId: string;
    client?: SzamlazzClient;
  }
): Promise<{ ok: boolean; invoiceNumber?: string; pdfBlobPath?: string; error?: string }> {
  const { quoteId, brand, tenantId } = params;
  const quotesColl = db.collection('quotes');

  let quote: any;
  if (ObjectId.isValid(quoteId)) {
    quote = await quotesColl.findOne({ _id: new ObjectId(quoteId), tenantId });
  } else {
    quote = await quotesColl.findOne({ _id: quoteId as any, tenantId });
  }

  if (!quote) {
    return { ok: false, error: 'Quote not found' };
  }

  const client = params.client || new SzamlazzClient();

  // Map quote line items
  const items = (quote.lineItems || []).map((li: any) => {
    const qty = li.quantity || 1;
    const unitPrice = li.unitPrice || li.value || 0;
    const netTotal = li.value || qty * unitPrice;
    return {
      name: li.label || 'SaaS Service',
      quantity: qty,
      unit: 'db',
      netUnitPrice: unitPrice,
      vatRate: '27',
      netTotal,
      vatTotal: netTotal * 0.27,
      grossTotal: netTotal * 1.27,
    };
  });

  const buyerName = quote.signerName || quote.entityName || 'Customer';
  const buyerEmail = quote.signerEmail;

  const result = await client.createProforma({
    currency: quote.currency || 'EUR',
    orderNumber: quote._id.toString(),
    buyer: {
      name: buyerName,
      email: buyerEmail,
    },
    items: items.length > 0 ? items : [
      {
        name: 'Service Package',
        quantity: 1,
        unit: 'db',
        netUnitPrice: quote.totalValue || 0,
        vatRate: '27',
        netTotal: quote.totalValue || 0,
        vatTotal: (quote.totalValue || 0) * 0.27,
        grossTotal: (quote.totalValue || 0) * 1.27,
      },
    ],
    comment: `Generated by SLG for Moldován Csaba Kft. Quote #${quoteId}`,
  });

  if (!result.ok) {
    return { ok: false, error: result.error };
  }

  // Update quote with invoiceNumber
  await quotesColl.updateOne(
    { _id: quote._id },
    {
      $set: {
        proformaInvoiceNumber: result.invoiceNumber,
        proformaIssuedAt: new Date().toISOString(),
        proformaNetTotal: result.netTotal,
        proformaGrossTotal: result.grossTotal,
      },
    }
  );

  return {
    ok: true,
    invoiceNumber: result.invoiceNumber,
  };
}
